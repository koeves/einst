#!/usr/bin/env python3
"""Generate Einst's v1-layout UI set into assets/ui-v1.

The layout comes from v1's own skin XML (assets/v1/Resources, read-only),
converted to the syntax dreist-gui reads (convert.py); every bitmap those
skins name is replaced by vector styling (looks.py) on the `Einst` theme
(theme.py: v1's palette, Liberation Sans for Arial). No v1 image is read
or copied. Einst's own assets that the set still needs (fonts, cursors,
metronome sounds, app icon) are copied from assets/ui, which the current
editor keeps using and this script never writes.

Pure Python 3 (standard library only).

    python3 scripts/uigen/uigen.py            # writes assets/ui-v1
    python3 scripts/uigen/uigen.py --check    # fails if assets/ui-v1 is stale
    python3 scripts/uigen/uigen.py --report   # prints the class mapping and leftovers
"""

import hashlib
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import convert  # noqa: E402
import theme  # noqa: E402

ROOT = convert.ROOT
OUT = os.path.join(ROOT, "assets", "ui-v1")
OWN = os.path.join(ROOT, "assets", "ui")

# Einst's own files taken over from assets/ui (folders are copied whole).
COPIED = ["Fonts", "Cursors", "Metronomes", "AppIcon.icns", "AppIcon.png"]

HEADER = "Generated by scripts/uigen/uigen.py. Edit the generator, not this file."


def stylesheet(conv):
    out = {}
    colours = [convert.E("VColour", {"name": n, "colour": theme.colour_value(c)}) for n, c in theme.COLOURS.items()]
    seen = set(theme.COLOURS)
    v1 = []
    for n, c in conv.colours:
        if n not in seen:
            seen.add(n)
            v1.append(convert.E("VColour", {"name": n, "colour": theme.colour_value(c)}))
    if v1:
        v1[0].comment = "v1's named colours (code-drawn parts: grids, waves, envelopes, browser rows)"
    colours[0].comment = "Einst theme palette (v1's LCD palette plus the chassis colours)"
    out["Colours"] = colours + v1
    fonts = [convert.E("VFont", {"name": theme.text_font(s, b), "fontName": theme.TEXT_FAMILY, "fontSize": s, **({"weight": "bold"} if b else {})})
             for s, b in sorted(conv.fonts.used)]
    fonts += [convert.E("VFont", {"name": theme.icon_font(s), "fontName": theme.ICON_FAMILY, "fontSize": s}) for s in theme.ICON_SIZES]
    fonts[0].comment = "Liberation Sans stands in for v1's Arial (and Verdana); Einst-Icons for v1's image glyphs"
    out["Fonts"] = fonts
    styles = []
    for i, (name, attrs) in enumerate(theme.base_styles()):
        e = convert.E(theme.STYLE_CLASS.get(name, "CtrlStyle"), dict(name=name, **attrs))
        if i == 0:
            e.comment = "Theme styles (theme.py)"
        styles.append(e)
    last = None
    for source, name in conv.order:
        e = conv.styles[name][1]
        if source != last:
            e.comment = f"From v1 {source}"
            last = source
        styles.append(e)
    extra = [conv.extra[k] for k in sorted(conv.extra)]
    if extra:
        extra[0].comment = "Image-view looks (looks.IMAGES)"
    out["Styles"] = styles + extra
    return {f"Skin/Styles/Einst.style/{k}.stylesheet": convert.document(v, HEADER) for k, v in out.items()}


def gltinfo():
    lines = ["<root>", '    <vector name="defaultStyles">']
    for k in ("Colours", "Fonts", "Styles"):
        lines.append(f'        <VString string="/Styles/Einst.style/{k}.stylesheet" />')
    lines += ["    </vector>", "</root>"]
    return ("\n".join(lines) + "\n").encode()


def copied():
    files = {}
    for rel in COPIED:
        src = os.path.join(OWN, rel)
        if os.path.isdir(src):
            for dp, dns, fns in os.walk(src):
                dns.sort()
                for f in sorted(fns):
                    if f.startswith("."):
                        continue
                    p = os.path.join(dp, f)
                    files[os.path.relpath(p, OWN)] = open(p, "rb").read()
        else:
            files[rel] = open(src, "rb").read()
    return files


def check_names(files):
    """No legacy product or vendor name may reach the output."""
    bad = [n for n in (convert.PRODUCT, convert.VENDOR)]
    for rel, data in files.items():
        if rel.endswith((".skin", ".stylesheet", ".gltinfo")):
            text = data.decode("utf-8").lower()
            for b in bad:
                if b.lower() in text:
                    raise SystemExit(f"uigen: {rel} names a legacy product")


def outputs():
    conv = convert.Converter()
    conv.run()
    files = {f"Skin/{rel}": data for rel, data in conv.skins.items()}
    files.update(stylesheet(conv))
    files["Skin/project.gltinfo"] = gltinfo()
    check_names(files)
    files.update(copied())
    return files, conv


def report(conv):
    print("v1 class -> dreist-gui class (uses): how")
    for (a, b), n in sorted(conv.class_use.items()):
        print(f"  {a} -> {b} ({n}): {convert.CLASSES[a][1]}")
    print("style attributes:")
    for k, (d, how) in convert.STYLE_ATTRS.items():
        print(f"  {k} -> {d or '-'}: {how}")
    print("dropped controls:", conv.dropped_ctrls)
    print("decor panels:", conv.decor)
    print("bitmaps without a look rule:", conv.unmatched or "none")


def main():
    check = "--check" in sys.argv
    files, conv = outputs()
    if "--report" in sys.argv:
        report(conv)
        return
    stale = []
    for rel, data in sorted(files.items()):
        path = os.path.join(OUT, rel)
        old = open(path, "rb").read() if os.path.exists(path) else None
        if old == data:
            continue
        if check:
            stale.append(rel)
            continue
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "wb") as f:
            f.write(data)
        print("wrote", rel, hashlib.sha1(data).hexdigest()[:8])
    extra = []
    for dp, _, fns in os.walk(OUT):
        for f in fns:
            rel = os.path.relpath(os.path.join(dp, f), OUT)
            if rel not in files and not f.startswith("."):
                extra.append(rel)
    if extra:
        if check:
            stale += extra
        else:
            for rel in extra:
                os.remove(os.path.join(OUT, rel))
                print("removed", rel)
    if stale:
        print("stale:", ", ".join(sorted(stale)))
        sys.exit(1)


if __name__ == "__main__":
    main()
