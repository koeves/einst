#!/usr/bin/env python3
"""Generate Einst's v1-layout UI set into assets/ui-v1.

The layout is Einst's own description of v1's panels (skins/: one N()
tree per skin, the panel styles in skins/styles.py), written in the
syntax dreist-gui reads; every look is vector styling on the `Einst`
theme (theme.py: v1's palette, Liberation Sans for Arial). Skins v1 never
had (the standalone's device dialogs, effect panels for the newer effect
types) are authored in v1's style (authored.py). Einst's own assets that
the set still needs (fonts, cursors, metronome sounds, app icon) are
copied from assets/ui, which the current editor keeps using and this
script never writes.

Pure Python 3 (standard library only).

    python3 scripts/uigen/uigen.py            # writes assets/ui-v1
    python3 scripts/uigen/uigen.py --check    # fails if assets/ui-v1 is stale
"""

import hashlib
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import authored  # noqa: E402
import skins  # noqa: E402
import theme  # noqa: E402
from skins import E, document, styles  # noqa: E402

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
LEGACY_RS = os.path.join(ROOT, "commons", "crates", "dreist-formats", "src", "legacy.rs")
OUT = os.path.join(ROOT, "assets", "ui-v1")
OWN = os.path.join(ROOT, "assets", "ui")

# Einst's own files taken over from assets/ui (folders are copied whole).
COPIED = ["Fonts", "Cursors", "Metronomes", "AppIcon.icns", "AppIcon.png"]

HEADER = "Generated by scripts/uigen/uigen.py. Edit the generator, not this file."


def stylesheet():
    out = {}
    colours = [E("VColour", {"name": n, "colour": theme.colour_value(c)}) for n, c in theme.COLOURS.items()]
    named = [E("VColour", {"name": n, "colour": theme.colour_value(c)}) for n, c in styles.COLOURS]
    if named:
        named[0].comment = "v1's named colours (code-drawn parts: grids, waves, envelopes, browser rows)"
    colours[0].comment = "Einst theme palette (v1's LCD palette plus the chassis colours)"
    out["Colours"] = colours + named
    fonts = [E("VFont", {"name": theme.text_font(s, b), "fontName": theme.TEXT_FAMILY, "fontSize": s, **({"weight": "bold"} if b else {})})
             for s, b in sorted(set(theme.TEXT_SIZES) | set(styles.FONTS))]
    fonts += [E("VFont", {"name": theme.icon_font(s), "fontName": theme.ICON_FAMILY, "fontSize": s}) for s in theme.ICON_SIZES]
    fonts[0].comment = "Liberation Sans stands in for v1's Arial (and Verdana); Einst-Icons for v1's image glyphs"
    out["Fonts"] = fonts
    els = []
    for i, (name, attrs) in enumerate(theme.base_styles()):
        e = E(theme.STYLE_CLASS.get(name, "CtrlStyle"), dict(name=name, **attrs))
        if i == 0:
            e.comment = "Theme styles (theme.py)"
        els.append(e)
    for source, group in styles.STYLES:
        group[0].comment = f"From v1 {source}"
        els.extend(group)
    extra = list(styles.IMAGE_STYLES)
    if extra:
        extra[0].comment = "Image-view looks (looks.IMAGES)"
    out["Styles"] = els + extra
    return {f"Skin/Styles/Einst.style/{k}.stylesheet": document(v, HEADER) for k, v in out.items()}


def gltinfo():
    lines = ["<root>", '    <vector name="defaultStyles">']
    for k in ("Colours", "Fonts", "Styles"):
        lines.append(f'        <VString string="/Styles/Einst.style/{k}.stylesheet" />')
    lines += ["    </vector>", "</root>"]
    return ("\n".join(lines) + "\n").encode()


def copied():
    files = {}
    for rel in COPIED:
        src = os.path.join(OWN, rel)
        if os.path.isdir(src):
            for dp, dns, fns in os.walk(src):
                dns.sort()
                for f in sorted(fns):
                    if f.startswith("."):
                        continue
                    p = os.path.join(dp, f)
                    files[os.path.relpath(p, OWN)] = open(p, "rb").read()
        else:
            files[rel] = open(src, "rb").read()
    return files


def legacy_names():
    """The legacy product and vendor names, read from dreist-formats'
    legacy table (the one place they are spelled), to check the output
    against."""
    text = open(LEGACY_RS, encoding="utf-8").read()
    product = re.search(r'ROOT_ELEMENT: &str = "([^"]+)"', text).group(1)
    vendor = re.search(r'REVERB_TYPE: &str = "([^" ]+)', text).group(1)
    return product, vendor


def check_names(files):
    """No legacy product or vendor name may reach the output."""
    bad = legacy_names()
    for rel, data in files.items():
        if rel.endswith((".skin", ".stylesheet", ".gltinfo")):
            text = data.decode("utf-8").lower()
            for b in bad:
                if b.lower() in text:
                    raise SystemExit(f"uigen: {rel} names a legacy product")


def outputs():
    files = {f"Skin/{rel}": data for rel, data in skins.skins().items()}
    for rel, (elements, header) in authored.skins().items():
        if f"Skin/{rel}" in files:
            raise SystemExit(f"uigen: authored {rel} would replace a v1-layout skin")
        files[f"Skin/{rel}"] = document(elements, header)
    files.update(stylesheet())
    files["Skin/project.gltinfo"] = gltinfo()
    check_names(files)
    files.update(copied())
    return files


def main():
    check = "--check" in sys.argv
    files = outputs()
    stale = []
    for rel, data in sorted(files.items()):
        path = os.path.join(OUT, rel)
        old = open(path, "rb").read() if os.path.exists(path) else None
        if old == data:
            continue
        if check:
            stale.append(rel)
            continue
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "wb") as f:
            f.write(data)
        print("wrote", rel, hashlib.sha1(data).hexdigest()[:8])
    extra = []
    for dp, _, fns in os.walk(OUT):
        for f in fns:
            rel = os.path.relpath(os.path.join(dp, f), OUT)
            if rel not in files and not f.startswith("."):
                extra.append(rel)
    if extra:
        if check:
            stale += extra
        else:
            for rel in extra:
                os.remove(os.path.join(OUT, rel))
                print("removed", rel)
    if stale:
        print("stale:", ", ".join(sorted(stale)))
        sys.exit(1)


if __name__ == "__main__":
    main()
