# Bipolar parameters: knobs lit from the centre (v1's *C knob styles).
CENTRED = {"Balance", "Pitch", "Tone"}

W, H = 193, 150
COMBO_W, TOGGLE_CELL = 75, 44
# (the knobs' dial thickness as the v1-layout effect knobs have it, skins/effects.py)
LARGE = (50, 46, "LEDKnobLargeLR", "0.08")
SMALL = (24, 26, "LEDKnobSmallLR", "0.04")
CAPTION = 15


def _caption(cx, y, w, text):
    return E("CtrlLabel", {"name": "CtrlLabel", "rect": f"{cx - w // 2}, {y}, {w}, {CAPTION}", "style": "StandardLabelCenteredStyle", "text": text})


def _centres(n, width=W):
    """x centres of n equal cells across the panel."""
    cell = width / n
    return [int(round(cell * (i + 0.5))) for i in range(n)]


def effect_panel(params):
    """Controls of one effect panel: the combos and buttons in rows at the
    top, then the knobs in rows (large ones for up to three)."""
    tops = [(i, p) for i, p in enumerate(params) if p[1] != K]
    knobs = [(i, p) for i, p in enumerate(params) if p[1] == K]
    rows, row = [], []
    for item in tops:
        w = COMBO_W if item[1][1] == C else TOGGLE_CELL
        if row and sum(COMBO_W if r[1][1] == C else TOGGLE_CELL for r in row) + w > W - 6:
            rows.append(row)
            row = []
        row.append(item)
    if row:
        rows.append(row)
    kids = []
    y = 5
    for r in rows:
        widths = [COMBO_W if p[1] == C else TOGGLE_CELL for _, p in r]
        gap = (W - sum(widths)) / (len(r) + 1)
        x = gap
        for (i, (cap, kind)), w in zip(r, widths):
            cx = int(round(x + w / 2))
            name = f"Control{i + 1}"
            if kind == C:
                kids.append(E("CtrlPopupButton", {"name": name, "rect": f"{cx - COMBO_W // 2}, {y}, {COMBO_W}, 17", "displayName": cap,
                                                  "optSingleClickEdit": "true", "style": "LEDComboBoxStyle"}))
            else:
                kids.append(E("CtrlButton", {"name": name, "rect": f"{cx - 8}, {y}, 16, 17", "displayName": cap, "optIsMomentary": "false",
                                             "style": "LEDSmallLatchingButtonStyle", "text": ""}))
            kids.append(_caption(cx, y + 19, max(w, 44) + 8, cap))
            x += w + gap
        y += 19 + CAPTION + 3
    n = len(knobs)
    if n:
        kw, kh, style, thick = LARGE if n <= 3 else SMALL
        per_row = n if n <= 3 else (4 if n in (4, 7, 8) else 3)
        lines = [knobs[k:k + per_row] for k in range(0, n, per_row)]
        block = kh + 4 + CAPTION
        free = H - 4 - y
        pitch = max(block + 2, free // len(lines))
        top = y + max(0, (free - pitch * (len(lines) - 1) - block) // 2)
        for li, line in enumerate(lines):
            ky = top + li * pitch
            # Each row on the full grid of its widest row, so columns line up.
            for (i, (cap, _)), cx in zip(line, _centres(per_row)):
                st = style.replace("LR", "C") if cap in CENTRED and style == LARGE[2] else style
                kids.append(E("CtrlKnob", {"name": f"Control{i + 1}", "rect": f"{cx - kw // 2}, {ky}, {kw}, {kh}", "displayName": cap,
                                           "realDialThickness": thick, "style": st}))
                kids.append(_caption(cx, ky + kh + 4, min(66, W // per_row + 4), cap))
    return [E("CtrlPanel", {"name": "CtrlPanel", "rect": f"0, 0, {W}, {H}", "style": "EmptyPanelStyle"}, kids)]


def skins():
    """rel path -> (elements, header)."""
    out = {}
    for rel, (fn, what) in DIALOGS.items():
        out[rel] = (fn(), HEADER.format(what=what))
    for kind, (name, params) in sorted(EFFECTS.items()):
        out[f"Effects/{name}.skin"] = (effect_panel(params), HEADER.format(what=f"effect type {kind}"))
    return out
