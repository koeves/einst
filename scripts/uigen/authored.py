"""Skins v1 never shipped, authored here in v1's style.

- The standalone app's device dialogs and the MIDI console (v1 had no
  standalone app): the same chrome as v1's Preferences / Export panels
  (ModalPanelStyle, grouped ModalPanelCollectionStyle boxes, ModalLabel
  captions, Modal combo boxes and buttons), with the control names the
  editor binds (crates/einst-editor/src/devices.rs, midiconsole.rs).
- Effect panels for the effect types v1 had no skin for: v1's slot size
  (193 x 150) and v1's effect-skin vocabulary (LED knobs, LED combo boxes,
  small latching buttons, centred captions), laid out from each type's
  front-panel parameter list (dreist_formats::params::effect_param_names;
  combos where effect_option_strings has items, latching buttons for the
  on / off ports of dreist_dsp's port tables). Control<n> drives
  parameter n - 1, as in v1's effect skins.
"""

from skins import E

HEADER = "Generated by scripts/uigen (authored in v1's style: {what}). Edit the generator, not this file."

# ---------------------------------------------------------------- dialogs


def _label(x, y, w, text, style="ModalLabelStyle", h=15, name="CtrlLabel"):
    return E("CtrlLabel", {"name": name, "rect": f"{x}, {y}, {w}, {h}", "style": style, "text": text})


def _button(name, x, y, w, text, momentary=True, style=None, h=17, display=None):
    a = {"name": name, "rect": f"{x}, {y}, {w}, {h}", "optIsMomentary": "true" if momentary else "false",
         "style": style or ("ModalMomentaryButtonStyle" if momentary else "ModalLatchingButtonStyle"), "text": text}
    if display:
        a["displayName"] = display
    return E("CtrlButton", a)


def _combo(name, x, y, w, display):
    return E("CtrlPopupButton", {"name": name, "rect": f"{x}, {y}, {w}, 17", "displayName": display, "optSingleClickEdit": "true",
                                 "style": "ModalComboBoxStyle"})


def _group(x, y, w, h, kids, name="CtrlPanel"):
    return E("CtrlPanel", {"name": name, "rect": f"{x}, {y}, {w}, {h}", "style": "ModalPanelCollectionStyle"}, kids)


def _table(name, x, y, w, h):
    return E("CtrlTableView", {"name": name, "rect": f"{x}, {y}, {w}, {h}", "style": "GlobalTableStyle"})


# The check box the editor's tables were modelled on (hidden by the
# editor, kept for the control names).
def _check_template(x, y):
    return E("CtrlButton", {"name": "CheckBox", "rect": f"{x}, {y}, 14, 15", "optIsMomentary": "false", "renderer": "CheckBoxButtonRenderer",
                            "style": "ModalCheckButtonStyle", "text": ""})


def audio_options():
    """Audio device dialog (320 x 380): device, rate and buffer in one
    group, the channel table under INPUTS / OUTPUTS tabs, then Rescan,
    Cancel and OK."""
    rows = [("Output device", "OutDevice", 190), ("Input device", "InDevice", 190), ("Sample rate", "SampleRate", 100),
            ("Buffer size", "BufferSize", 100)]
    kids = []
    for i, (cap, name, w) in enumerate(rows):
        y = 8 + 22 * i
        kids.append(_label(-8, y + 1, 110, cap, "ModalLabelRightAlignedStyle"))
        kids.append(_combo(name, 108, y, w, cap))
    # The Windows driver panel (hidden by the editor: the Mac has none).
    kids.append(E("CtrlPanel", {"name": "WinSettingPanel", "rect": "0, 96, 308, 22", "style": "EmptyPanelStyle"}, [
        _combo("ASIODevice", 108, 0, 120, "Driver"),
        _button("ASIOButton", 232, 0, 66, "Settings"),
    ]))
    panel = E("CtrlPanel", {"name": "CtrlPanel", "rect": "0, 0, 320, 380", "style": "ModalPanelStyle"}, [
        _label(7, 5, 150, "Audio Device"),
        _group(6, 22, 308, 98, kids),
        _label(7, 126, 150, "Channels"),
        E("CtrlButtonGroup", {"name": "IOGroup", "rect": "6, 143, 120, 17", "style": "BasePanelStyle"}, [
            _button("CtrlButton", 0, 0, 61, "Inputs", momentary=False),
            _button("CtrlButton", 59, 0, 61, "Outputs", momentary=False),
        ]),
        _table("IOTable", 6, 163, 308, 180),
        _check_template(140, 355),
        _button("Refresh", 6, 355, 60, "Rescan", display="Look for audio devices again"),
        _button("Cancel", 200, 355, 55, "Cancel", display="Discard the changes"),
        _button("Close", 259, 355, 55, "OK", display="Keep the changes (audio restarts when they changed)"),
    ])
    return [panel]


