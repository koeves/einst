"""Einst's v1-layout skins: a small layout language and the XML writer.

Every `.skin` under assets/ui-v1/Skin is generated from the panel modules
next to this file (`effects.py`, `mixer.py`, ...), one function per skin
(`@skin("Folder/Name.skin")`), plus the styles in `styles.py`. A panel is a
tree of `N` nodes: a dreist-gui control class (`"Knob"` for `CtrlKnob`), an
optional name (the editor finds controls by name), a rect relative to the
parent and any other skin attributes (dreist-gui's names: `style`, `id`,
`displayName`, `text`, `overloadClass`, ...). The layout follows v1's: the
same rects, names, ids and texts, so the editor binds the same controls;
`legacyClass` names the v1 control a node stands in for where dreist-gui
draws it as another class. Panels with no name and only a `style` are
vector decor (frames, LEDs, knob bodies) where v1 drew bitmaps.

Styles are `S` entries: a name, the parent style it builds on (the theme's
base styles, theme.py) and its attributes.
"""

import importlib
import pkgutil


class E:
    """A skin or stylesheet element: class, attributes, children."""

    def __init__(self, cls, attrs=None, kids=None, comment=None):
        self.cls, self.attrs, self.kids, self.comment = cls, dict(attrs or {}), list(kids or []), comment


def _fmt(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (tuple, list)):
        return ", ".join(str(x) for x in v)
    return str(v)


def N(cls, name=None, rect=None, kids=(), **attrs):
    """A control: `N("Knob", "Control1", (x, y, w, h), style=..., kids=[...])`."""
    a = {}
    if name is not None:
        a["name"] = name
    if rect is not None:
        a["rect"] = rect
    a.update(attrs)
    return E(cls if cls.startswith("Ctrl") else "Ctrl" + cls, {k: _fmt(v) for k, v in a.items()}, kids)


def S(name, parent, cls="CtrlStyle", **attrs):
    """A style named `name` built on `parent`."""
    return E(cls, {"name": name, "parentStyle0": parent, **{k: _fmt(v) for k, v in attrs.items()}})


def esc(v):
    return (v.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace('"', "&quot;")
            .replace("\n", "&#10;").replace("\t", "&#9;"))


FIRST = ["name", "rect"]


def write(e, depth=1):
    pad = "    " * depth
    out = []
    if e.comment:
        out.append(f"{pad}<!-- {e.comment} -->")
    keys = [k for k in FIRST if k in e.attrs] + sorted(k for k in e.attrs if k not in FIRST)
    a = "".join(f' {k}="{esc(str(e.attrs[k]))}"' for k in keys)
    if e.kids:
        out.append(f"{pad}<{e.cls}{a}>")
        for k in e.kids:
            out.extend(write(k, depth + 1))
        out.append(f"{pad}</{e.cls}>")
    else:
        out.append(f"{pad}<{e.cls}{a} />")
    return out


def document(elements, header):
    lines = [f"<!-- {header} -->", "<root>"]
    for e in elements:
        lines.extend(write(e))
    lines.append("</root>")
    return ("\n".join(lines) + "\n").encode("utf-8")


# ---------------------------------------------------------------- registry

_SKINS = {}  # output rel -> (layout origin, function)


def skin(rel, origin=None):
    """Registers the decorated function as the skin at `Skin/<rel>`
    (`origin`: the v1 layout file it follows, when named differently)."""

    def register(f):
        if rel in _SKINS:
            raise SystemExit(f"uigen: two skins for {rel}")
        _SKINS[rel] = (origin or rel, f)
        return f

    return register


def skins():
    """{rel: document bytes} for every panel module's skins."""
    for m in pkgutil.iter_modules(__path__):
        importlib.import_module(f"{__name__}.{m.name}")
    out = {}
    for rel, (origin, f) in _SKINS.items():
        header = f"Generated by scripts/uigen from the v1 layout ({origin}). Edit the generator, not this file."
        out[rel] = document(f(), header)
    return out
